// "2026-11-23T09:12:00+05:30": today in Sri Lanka at a set time
// "YYYY-MM-DD", some days after today in Sri Lanka
function dayAfter(now: Date, days: number): string {
  return new Date(now.getTime() + days * 86_400_000).toLocaleDateString("en-CA", { timeZone: "Asia/Colombo" });
}

function todayAt(now: Date, time: string, daysAgo = 0): string {
  const day = new Date(now.getTime() - daysAgo * 86_400_000).toLocaleDateString("en-CA", { timeZone: "Asia/Colombo" });
  return `${day}T${time}:00+05:30`;
}

const at = (day: string, time = "10:00") => `${day}T${time}:00+05:30`;

